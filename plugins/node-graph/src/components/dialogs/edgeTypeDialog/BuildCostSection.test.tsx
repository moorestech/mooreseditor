function createBlocksMeta(): SchemaMeta {
  return {
    schemaId: "blocks",
    guidField: "blockGuid",
    nameField: "name",
    dataArrayPath: "data",
    elementSchema: {
      type: "object",
      properties: [
        { key: "blockGuid", type: "uuid", autoGenerated: true },
        {
          key: "requiredItems",
          type: "array",
          items: {
            type: "object",
            properties: [
              {
                key: "itemGuid",
                type: "uuid",
                foreignKey: { schemaId: "items" },
              },
              { key: "count", type: "integer" },
            ],
          },
        },
      ],
    },
  } as unknown as SchemaMeta;
}

// 実フック(useEdgeTypeDialogState)と実BuildCostSectionを配線した統合ハーネス
// Integration harness wiring the real hook and the real BuildCostSection
function Harness({ latest }: { latest: { columns: Column[] } }) {
  const [columns, setColumns] = useState<Column[]>([
    {
      title: "blocks",
      data: {
        data: [
          {
            blockGuid: "block-b",
            requiredItems: [{ itemGuid: "item-x", count: 5 }],
          },
        ],
      },
    },
  ]);
  latest.columns = columns;

  const schemaMetas = new Map([["blocks", createBlocksMeta()]]);
  const targetNode = {
    id: "target",
    type: "block",
    data: { masterGuid: "block-b" },
  } as never;

  const dialog = useEdgeTypeDialogState({
    opened: true,
    onConfirm: () => {},
    onCancel: () => {},
    jsonData: columns,
    setJsonData: setColumns,
    schemaMetas,
    sourceNode: null,
    targetNode,
    onMarkDirty: () => {},
  });

  return (
    <>
      <BuildCostSection
        targetNode={targetNode}
        jsonData={columns}
        setJsonData={setColumns}
        schemaMetas={schemaMetas}
        onMarkDirty={() => {}}
        onRegisterCostSnapshot={dialog.registerCostSnapshot}
      />
      <button type="button" data-testid="cancel" onClick={dialog.handleCancel}>
        cancel
      </button>
    </>
  );
}

function requiredItemsOf(latest: { columns: Column[] }) {
  return (
    latest.columns[0].data.data as {
      requiredItems: { itemGuid: string; count: number }[];
    }[]
  )[0].requiredItems;
}

describe("BuildCostSection integration", () => {
  it("captures the pre-edit value on first edit and restores it on cancel", () => {
    const latest = { columns: [] as Column[] };
    render(
      <MantineProvider>
        <Harness latest={latest} />
      </MantineProvider>,
    );

    // 2回編集: 初回スナップショット(count5)がfirst-winsで保持されるはず
    // Edit twice: the first snapshot (count 5) must win over later edits
    fireEvent.click(screen.getByTestId("mutate"));
    expect(requiredItemsOf(latest)[0].count).toBe(6);
    fireEvent.click(screen.getByTestId("mutate"));
    expect(requiredItemsOf(latest)[0].count).toBe(7);

    fireEvent.click(screen.getByTestId("cancel"));
    expect(requiredItemsOf(latest)).toEqual([
      { itemGuid: "item-x", count: 5 },
    ]);
  });
});
