import { act, renderHook } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";

import { useEdgeTypeDialogState } from "./useEdgeTypeDialogState";

import type { SchemaMeta } from "../../../utils/schemaMeta";
import type { Column } from "@moorestech/mooreseditor-plugin-sdk";

function createCraftRecipeMeta(): SchemaMeta {
  return {
    schemaId: "craftRecipes",
    guidField: "craftRecipeGuid",
    nameField: "craftRecipeName",
    dataArrayPath: "data",
    elementSchema: {
      type: "object",
      properties: [
        { key: "craftRecipeGuid", type: "uuid", autoGenerated: true },
        { key: "craftRecipeName", type: "string", default: "Recipe" },
      ],
    },
  };
}

describe("useEdgeTypeDialogState", () => {
  it("removes a newly created draft recipe when the dialog is cancelled", () => {
    let columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const setJsonData = vi.fn((updater) => {
      columns = typeof updater === "function" ? updater(columns) : updater;
    });

    const { result } = renderHook(() =>
      useEdgeTypeDialogState({
        opened: true,
        onConfirm: vi.fn(),
        onCancel: vi.fn(),
        jsonData: columns,
        setJsonData,
        schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
        sourceNode: {
          id: "source",
          type: "item",
          data: { masterGuid: "item-a" },
        } as any,
        targetNode: {
          id: "target",
          type: "item",
          data: { masterGuid: "item-b" },
        } as any,
        onMarkDirty: vi.fn(),
      }),
    );

    act(() => {
      result.current.handleCreateRecipe("craftRecipe");
    });
    expect(columns[0].data.data).toHaveLength(1);

    act(() => {
      result.current.handleCancel();
    });

    expect(columns[0].data.data).toHaveLength(0);
  });

  it("does not reset the selected recipes when rerendered while open", () => {
    const columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const setJsonData = vi.fn();
    const onConfirm = vi.fn();

    const createProps = () => ({
      opened: true,
      onConfirm,
      onCancel: vi.fn(),
      jsonData: columns,
      setJsonData,
      schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
      sourceNode: {
        id: "source",
        type: "item",
        data: { masterGuid: "item-a" },
      } as any,
      targetNode: {
        id: "target",
        type: "item",
        data: { masterGuid: "item-b" },
      } as any,
      onMarkDirty: vi.fn(),
      initialRecipeRefs: [
        { edgeType: "craftRecipe" as const, masterGuid: "initial-guid" },
      ],
    });

    const { result, rerender } = renderHook(
      (props: ReturnType<typeof createProps>) =>
        useEdgeTypeDialogState(props),
      { initialProps: createProps() },
    );

    expect(result.current.craftRecipeGuids).toEqual(["initial-guid"]);

    act(() => {
      result.current.setCraftRecipeGuids(["user-selected-guid"]);
    });

    rerender(createProps());

    expect(result.current.craftRecipeGuids).toEqual(["user-selected-guid"]);
  });

  it("preselects the edited edge's current type from initialMode", () => {
    const columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const createProps = (opened: boolean) => ({
      opened,
      onConfirm: vi.fn(),
      onCancel: vi.fn(),
      jsonData: columns,
      setJsonData: vi.fn(),
      schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
      sourceNode: {
        id: "source",
        type: "item",
        data: { masterGuid: "item-a" },
      } as any,
      targetNode: {
        id: "target",
        type: "block",
        data: { masterGuid: "block-b" },
      } as any,
      onMarkDirty: vi.fn(),
      initialMode: "buildCost" as const,
    });

    const { result } = renderHook(
      (props: ReturnType<typeof createProps>) => useEdgeTypeDialogState(props),
      { initialProps: createProps(true) },
    );

    expect(result.current.mode).toBe("buildCost");
  });

  it("falls back to dependency and blocks confirm when buildCost is unavailable", () => {
    const columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const onConfirm = vi.fn();
    const createProps = () => ({
      opened: true,
      onConfirm,
      onCancel: vi.fn(),
      jsonData: columns,
      setJsonData: vi.fn(),
      schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
      sourceNode: {
        id: "source",
        type: "item",
        data: { masterGuid: "item-a" },
      } as any,
      targetNode: {
        id: "target",
        type: "item",
        data: { masterGuid: "item-b" },
      } as any,
      onMarkDirty: vi.fn(),
      initialMode: "buildCost" as const,
    });

    const { result } = renderHook(
      (props: ReturnType<typeof createProps>) => useEdgeTypeDialogState(props),
      { initialProps: createProps() },
    );

    expect(result.current.isBuildCostAvailable).toBe(false);
    expect(result.current.mode).toBe("dependency");

    act(() => {
      result.current.setMode("buildCost");
    });
    act(() => {
      result.current.handleConfirm();
    });
    expect(onConfirm).not.toHaveBeenCalled();
  });

  it("resets stale mode and recipe selections when reopened without initial state", () => {
    const columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const createProps = (opened: boolean) => ({
      opened,
      onConfirm: vi.fn(),
      onCancel: vi.fn(),
      jsonData: columns,
      setJsonData: vi.fn(),
      schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
      sourceNode: {
        id: "source",
        type: "item",
        data: { masterGuid: "item-a" },
      } as any,
      targetNode: {
        id: "target",
        type: "item",
        data: { masterGuid: "item-b" },
      } as any,
      onMarkDirty: vi.fn(),
    });

    const { result, rerender } = renderHook(
      (props: ReturnType<typeof createProps>) => useEdgeTypeDialogState(props),
      { initialProps: createProps(true) },
    );

    act(() => {
      result.current.setMode("recipe");
      result.current.setCraftRecipeGuids(["stale-guid"]);
    });

    rerender(createProps(false));
    rerender(createProps(true));

    expect(result.current.mode).toBe("dependency");
    expect(result.current.craftRecipeGuids).toEqual([]);
  });

  it("restores snapshotted build-cost edits on cancel but keeps them on confirm", () => {
    const originalItems = [{ itemGuid: "item-x", count: 5 }];
    let columns: Column[] = [
      {
        title: "blocks",
        data: { data: [{ blockGuid: "block-b", requiredItems: originalItems }] },
      },
    ];
    const setJsonData = vi.fn((updater) => {
      columns = typeof updater === "function" ? updater(columns) : updater;
    });
    const createProps = () => ({
      opened: true,
      onConfirm: vi.fn(),
      onCancel: vi.fn(),
      jsonData: columns,
      setJsonData,
      schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
      sourceNode: {
        id: "source",
        type: "item",
        data: { masterGuid: "item-a" },
      } as any,
      targetNode: {
        id: "target",
        type: "block",
        data: { masterGuid: "block-b" },
      } as any,
      onMarkDirty: vi.fn(),
    });

    const { result } = renderHook(
      (props: ReturnType<typeof createProps>) => useEdgeTypeDialogState(props),
      { initialProps: createProps() },
    );

    // 編集をシミュレート: スナップショット登録の後にデータを書き換える
    // Simulate an edit: register the snapshot, then mutate the data
    act(() => {
      result.current.registerCostSnapshot({
        schemaId: "blocks",
        dataArrayPath: "data",
        guidField: "blockGuid",
        guid: "block-b",
        propertyKey: "requiredItems",
        original: originalItems,
      });
    });
    columns = [
      {
        title: "blocks",
        data: {
          data: [
            { blockGuid: "block-b", requiredItems: [{ itemGuid: "item-x", count: 9 }] },
          ],
        },
      },
    ];

    act(() => {
      result.current.handleCancel();
    });

    expect(columns[0].data.data[0].requiredItems).toEqual(originalItems);
  });

  it("keeps snapshotted build-cost edits when the dialog is confirmed", () => {
    const originalItems = [{ itemGuid: "item-x", count: 5 }];
    const editedItems = [{ itemGuid: "item-x", count: 9 }];
    let columns: Column[] = [
      {
        title: "blocks",
        data: { data: [{ blockGuid: "block-b", requiredItems: editedItems }] },
      },
    ];
    const setJsonData = vi.fn((updater) => {
      columns = typeof updater === "function" ? updater(columns) : updater;
    });

    const { result } = renderHook(() =>
      useEdgeTypeDialogState({
        opened: true,
        onConfirm: vi.fn(),
        onCancel: vi.fn(),
        jsonData: columns,
        setJsonData,
        schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
        sourceNode: {
          id: "source",
          type: "item",
          data: { masterGuid: "item-a" },
        } as any,
        targetNode: {
          id: "target",
          type: "block",
          data: { masterGuid: "block-b" },
        } as any,
        onMarkDirty: vi.fn(),
      }),
    );

    act(() => {
      result.current.registerCostSnapshot({
        schemaId: "blocks",
        dataArrayPath: "data",
        guidField: "blockGuid",
        guid: "block-b",
        propertyKey: "requiredItems",
        original: originalItems,
      });
    });

    act(() => {
      result.current.handleConfirm();
    });
    // Confirmは編集を保持し、以後のCancelでも復元されない
    // Confirm keeps the edits; a later cancel must not restore them
    act(() => {
      result.current.handleCancel();
    });

    expect(columns[0].data.data[0].requiredItems).toEqual(editedItems);
  });

  it("removes only unselected draft recipes when the dialog is confirmed", () => {
    let columns: Column[] = [{ title: "craftRecipes", data: { data: [] } }];
    const setJsonData = vi.fn((updater) => {
      columns = typeof updater === "function" ? updater(columns) : updater;
    });
    const onConfirm = vi.fn();

    const { result } = renderHook(() =>
      useEdgeTypeDialogState({
        opened: true,
        onConfirm,
        onCancel: vi.fn(),
        jsonData: columns,
        setJsonData,
        schemaMetas: new Map([["craftRecipes", createCraftRecipeMeta()]]),
        sourceNode: {
          id: "source",
          type: "item",
          data: { masterGuid: "item-a" },
        } as any,
        targetNode: {
          id: "target",
          type: "item",
          data: { masterGuid: "item-b" },
        } as any,
        onMarkDirty: vi.fn(),
      }),
    );

    act(() => {
      result.current.handleCreateRecipe("craftRecipe");
      result.current.handleCreateRecipe("craftRecipe");
    });

    const [selectedGuid, unselectedGuid] = result.current.craftRecipeGuids;
    expect(columns[0].data.data).toHaveLength(2);

    act(() => {
      result.current.setCraftRecipeGuids([selectedGuid]);
    });

    act(() => {
      result.current.handleConfirm();
    });

    const remainingGuids = columns[0].data.data.map(
      (row: Record<string, unknown>) => row.craftRecipeGuid,
    );
    expect(remainingGuids).toEqual([selectedGuid]);
    expect(remainingGuids).not.toContain(unselectedGuid);
    expect(onConfirm).toHaveBeenCalledWith({
      edgeType: "recipe",
      recipeRefs: [{ edgeType: "craftRecipe", masterGuid: selectedGuid }],
    });
  });
});
