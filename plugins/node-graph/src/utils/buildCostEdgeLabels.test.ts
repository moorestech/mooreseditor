import { describe, expect, it } from "vitest";

import {
  buildBuildCostLabel,
  resolveBuildCostEdgeLabels,
} from "./buildCostEdgeLabels";
import { buildForeignNameResolver } from "./recipeEdgeLabels";

import type { SchemaMeta } from "./schemaMeta";
import type { Column } from "@moorestech/mooreseditor-plugin-sdk";
import type {
  Edge as ReactFlowEdge,
  Node as ReactFlowNode,
} from "@xyflow/react";

// --- Test fixtures ---

const IRON_GUID = "iron-1111";
const WOOD_GUID = "wood-2222";
const BLOCK_GUID = "block-3333";
const TRAIN_GUID = "train-4444";

function makeItemsColumn(): Column {
  return {
    title: "items",
    data: {
      data: [
        { itemGuid: IRON_GUID, name: "Iron Plate" },
        { itemGuid: WOOD_GUID, name: "Wood" },
      ],
    },
  };
}

function makeItemsMeta(): SchemaMeta {
  return {
    schemaId: "items",
    guidField: "itemGuid",
    nameField: "name",
    dataArrayPath: "data",
    elementSchema: {
      type: "object",
      properties: [
        { key: "itemGuid", type: "uuid", autoGenerated: true },
        { key: "name", type: "string" },
      ],
    },
  };
}

function makeBlocksMeta(): SchemaMeta {
  return {
    schemaId: "blocks",
    guidField: "blockGuid",
    nameField: "name",
    dataArrayPath: "data",
    elementSchema: {
      type: "object",
      properties: [
        { key: "blockGuid", type: "uuid", autoGenerated: true },
        { key: "name", type: "string" },
        {
          key: "requiredItems",
          type: "array",
          items: {
            type: "object",
            properties: [
              {
                key: "itemGuid",
                type: "uuid",
                foreignKey: {
                  schemaId: "items",
                  foreignKeyIdPath: "",
                  displayElementPath: "",
                },
              },
              { key: "count", type: "integer" },
            ],
          },
        },
      ],
    },
  };
}

function makeTrainMeta(): SchemaMeta {
  return {
    schemaId: "train",
    guidField: "trainCarGuid",
    nameField: "name",
    dataArrayPath: "trainCars",
    elementSchema: {
      type: "object",
      properties: [
        { key: "trainCarGuid", type: "uuid", autoGenerated: true },
        { key: "name", type: "string" },
        {
          key: "requiredItems",
          type: "array",
          items: {
            type: "object",
            properties: [
              {
                key: "itemGuid",
                type: "uuid",
                foreignKey: {
                  schemaId: "items",
                  foreignKeyIdPath: "",
                  displayElementPath: "",
                },
              },
              { key: "count", type: "integer" },
            ],
          },
        },
      ],
    },
  };
}

function makeColumns(): Column[] {
  return [
    makeItemsColumn(),
    {
      title: "blocks",
      data: {
        data: [
          {
            blockGuid: BLOCK_GUID,
            name: "Assembler",
            requiredItems: [
              { itemGuid: IRON_GUID, count: 5 },
              { itemGuid: WOOD_GUID, count: 1 },
            ],
          },
        ],
      },
    },
    {
      title: "train",
      data: {
        trainCars: [
          {
            trainCarGuid: TRAIN_GUID,
            name: "Steam Locomotive",
            requiredItems: [{ itemGuid: IRON_GUID, count: 20 }],
          },
        ],
      },
    },
  ];
}

function makeMetas(): Map<string, SchemaMeta> {
  return new Map([
    ["items", makeItemsMeta()],
    ["blocks", makeBlocksMeta()],
    ["train", makeTrainMeta()],
  ]);
}

function makeTargetNode(
  type: string,
  masterGuid: string,
  id = "target",
): ReactFlowNode {
  return { id, type, position: { x: 0, y: 0 }, data: { masterGuid } };
}

function resolver(columns: Column[], metas: Map<string, SchemaMeta>) {
  return buildForeignNameResolver(columns, metas);
}

describe("buildBuildCostLabel", () => {
  it("formats block requiredItems as 'name xCount' lines", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const label = buildBuildCostLabel(
      makeTargetNode("block", BLOCK_GUID),
      columns,
      metas,
      resolver(columns, metas),
    );
    expect(label).toBe("Iron Plate x5\nWood");
  });

  it("resolves train car requiredItems via the train schema", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const label = buildBuildCostLabel(
      makeTargetNode("train", TRAIN_GUID),
      columns,
      metas,
      resolver(columns, metas),
    );
    expect(label).toBe("Iron Plate x20");
  });

  it("falls back to shortGuid for unresolvable material names", () => {
    const columns = makeColumns();
    const blocksColumn = columns.find((c) => c.title === "blocks")!;
    blocksColumn.data.data[0].requiredItems = [
      { itemGuid: "unknown-material-guid", count: 2 },
    ];
    const metas = makeMetas();
    const label = buildBuildCostLabel(
      makeTargetNode("block", BLOCK_GUID),
      columns,
      metas,
      resolver(columns, metas),
    );
    expect(label).toBe("unknown- x2");
  });

  it("returns null when the target record has no requiredItems", () => {
    const columns = makeColumns();
    const blocksColumn = columns.find((c) => c.title === "blocks")!;
    delete blocksColumn.data.data[0].requiredItems;
    const metas = makeMetas();
    const label = buildBuildCostLabel(
      makeTargetNode("block", BLOCK_GUID),
      columns,
      metas,
      resolver(columns, metas),
    );
    expect(label).toBeNull();
  });

  it("returns null when the target record is missing (dangling)", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const label = buildBuildCostLabel(
      makeTargetNode("block", "dangling-guid"),
      columns,
      metas,
      resolver(columns, metas),
    );
    expect(label).toBeNull();
  });
});

describe("resolveBuildCostEdgeLabels", () => {
  function makeBuildCostEdge(target: string): ReactFlowEdge {
    return {
      id: "e1",
      source: "src",
      target,
      type: "buildCost",
      data: { edgeType: "buildCost" },
    };
  }

  it("bakes labels into buildCost edges", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const nodes = [makeTargetNode("block", BLOCK_GUID, "b1")];
    const edges = [makeBuildCostEdge("b1")];
    const [resolved] = resolveBuildCostEdgeLabels(edges, nodes, columns, metas);
    expect(resolved.data?.buildCostLabel).toBe("Iron Plate x5\nWood");
  });

  it("returns the same reference for non-buildCost edges", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const edge: ReactFlowEdge = {
      id: "e1",
      source: "a",
      target: "b",
      data: { edgeType: "dependency" },
    };
    const [resolved] = resolveBuildCostEdgeLabels([edge], [], columns, metas);
    expect(resolved).toBe(edge);
  });

  it("returns the same reference when the label is unchanged", () => {
    const columns = makeColumns();
    const metas = makeMetas();
    const nodes = [makeTargetNode("block", BLOCK_GUID, "b1")];
    const edges = resolveBuildCostEdgeLabels(
      [makeBuildCostEdge("b1")],
      nodes,
      columns,
      metas,
    );
    const second = resolveBuildCostEdgeLabels(edges, nodes, columns, metas);
    expect(second[0]).toBe(edges[0]);
  });
});
